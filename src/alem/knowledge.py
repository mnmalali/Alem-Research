"""Controlled generation of the Obsidian-compatible knowledge index."""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from alem.workspace import Workspace

START = "<!-- alem:index:start -->"
END = "<!-- alem:index:end -->"


@dataclass(frozen=True, slots=True)
class KnowledgePage:
    title: str
    kind: str
    status: str
    relative: Path


def _frontmatter(text: str) -> dict[str, str]:
    if not text.startswith("---\n"):
        return {}
    closing = text.find("\n---", 4)
    if closing < 0:
        return {}
    values: dict[str, str] = {}
    for line in text[4:closing].splitlines():
        if ":" not in line or line.lstrip().startswith("#"):
            continue
        key, value = line.split(":", 1)
        values[key.strip()] = value.strip().strip('"\'')
    return values


def _title(text: str, fallback: str) -> str:
    match = re.search(r"(?m)^#\s+(.+?)\s*$", text)
    return match.group(1) if match else fallback


def scan_knowledge(workspace: Workspace) -> list[KnowledgePage]:
    root = workspace.path("knowledge")
    pages: list[KnowledgePage] = []
    for path in sorted(root.rglob("*.md")):
        is_maintenance = path.name.lower() in {"index.md", "readme.md", "changelog.md"}
        if is_maintenance or path.name.startswith("_"):
            continue
        text = path.read_text(encoding="utf-8")
        metadata = _frontmatter(text)
        pages.append(
            KnowledgePage(
                title=metadata.get("title") or _title(text, path.stem),
                kind=metadata.get("type", "note"),
                status=metadata.get("status", "unknown"),
                relative=path.relative_to(root),
            )
        )
    return pages


def update_index(workspace: Workspace) -> tuple[Path, int]:
    pages = scan_knowledge(workspace)
    grouped: dict[str, list[KnowledgePage]] = {}
    for page in pages:
        grouped.setdefault(page.kind, []).append(page)
    lines = [
        START,
        "",
        "_Generated by `alem knowledge index`; edit source pages, not this block._",
        "",
    ]
    for kind, items in sorted(grouped.items()):
        lines.extend((f"## {kind.replace('-', ' ').title()}", ""))
        for page in items:
            target = page.relative.with_suffix("").as_posix()
            lines.append(f"- [[{target}|{page.title}]] — `{page.status}`")
        lines.append("")
    lines.append(END)
    block = "\n".join(lines) + "\n"
    index = workspace.path("knowledge/index.md")
    current = (
        index.read_text(encoding="utf-8")
        if index.exists()
        else "# Alem knowledge index\n\n"
    )
    if START in current and END in current:
        prefix, remainder = current.split(START, 1)
        _, suffix = remainder.split(END, 1)
        content = prefix.rstrip() + "\n\n" + block + suffix.lstrip("\n")
    else:
        content = current.rstrip() + "\n\n" + block
    workspace.atomic_write_text("knowledge/index.md", content)
    return index, len(pages)
